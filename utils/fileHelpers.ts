
import { Attachment } from '../types';

export const fileToBase64 = (file: File): Promise<string> => {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.readAsDataURL(file);
    reader.onload = () => resolve(reader.result as string);
    reader.onerror = (error) => reject(error);
  });
};

export const readFileAsText = (file: File): Promise<string> => {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(reader.result as string);
    reader.onerror = reject;
    reader.readAsText(file);
  });
};

export const extractTextFromDocx = async (file: File): Promise<string> => {
  const mammoth = (window as any).mammoth;
  if (!mammoth) {
    throw new Error("Mammoth library not loaded");
  }
  
  const arrayBuffer = await file.arrayBuffer();
  const result = await mammoth.extractRawText({ arrayBuffer });
  return result.value;
};

export const processFile = async (file: File): Promise<Attachment> => {
  const isImage = file.type.startsWith('image/');
  const isPdf = file.type === 'application/pdf';
  const isDocx = file.name.endsWith('.docx') || file.type === 'application/vnd.openxmlformats-officedocument.wordprocessingml.document';
  const isText = file.type === 'text/plain' || file.name.endsWith('.md') || file.name.endsWith('.txt') || file.name.endsWith('.json') || file.name.endsWith('.csv');

  if (isImage) {
    const base64 = await fileToBase64(file);
    return {
      type: 'image',
      mimeType: file.type,
      data: base64,
      name: file.name
    };
  }

  if (isPdf) {
    const base64 = await fileToBase64(file);
    return {
      type: 'pdf',
      mimeType: 'application/pdf',
      data: base64,
      name: file.name
    };
  }

  if (isDocx) {
    const text = await extractTextFromDocx(file);
    return {
      type: 'text',
      mimeType: 'text/plain',
      textContent: text,
      name: file.name
    };
  }

  if (isText) {
    const text = await readFileAsText(file);
    return {
      type: 'text',
      mimeType: 'text/plain',
      textContent: text,
      name: file.name
    };
  }

  throw new Error("Unsupported file type. Please upload Image, PDF, DOCX, or Text files.");
};

export const copyToClipboard = async (text: string): Promise<boolean> => {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch (err) {
    console.error('Failed to copy:', err);
    return false;
  }
};

export const downloadAsDoc = (content: string, filename: string) => {
  // Simple Markdown to HTML converter for valid Word rendering
  const htmlContent = `
    <html xmlns:o='urn:schemas-microsoft-com:office:office' xmlns:w='urn:schemas-microsoft-com:office:word' xmlns='http://www.w3.org/TR/REC-html40'>
    <head>
      <meta charset='utf-8'>
      <title>Export</title>
      <style>
        body { font-family: Arial, sans-serif; line-height: 1.6; color: #000; }
        h1, h2, h3 { color: #2e2e2e; margin-top: 20px; }
        code { background: #f4f4f4; padding: 2px 5px; border-radius: 3px; font-family: monospace; }
        pre { background: #f4f4f4; padding: 10px; border-radius: 5px; white-space: pre-wrap; }
        blockquote { border-left: 4px solid #ccc; margin: 0; padding-left: 16px; color: #666; }
        ul, ol { margin: 10px 0; padding-left: 20px; }
      </style>
    </head>
    <body>
      ${content
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;")
        .replace(/^### (.*$)/gim, '<h3>$1</h3>')
        .replace(/^## (.*$)/gim, '<h2>$1</h2>')
        .replace(/^# (.*$)/gim, '<h1>$1</h1>')
        .replace(/\*\*(.*?)\*\*/gim, '<b>$1</b>')
        .replace(/\*(.*?)\*/gim, '<i>$1</i>')
        .replace(/```([\s\S]*?)```/gim, '<pre>$1</pre>')
        .replace(/`(.*?)`/gim, '<code>$1</code>')
        .replace(/^\> (.*$)/gim, '<blockquote>$1</blockquote>')
        .replace(/^\- (.*$)/gim, '<ul><li>$1</li></ul>') // Simple list support
        .replace(/^\d+\. (.*$)/gim, '<ol><li>$1</li></ol>')
        .replace(/\n/gim, '<br />')
      }
      <br/><br/>
      <p style="font-size: 10px; color: #888;">Generated by Haruna AI</p>
    </body>
    </html>
  `;

  const blob = new Blob(['\ufeff', htmlContent], {
    type: 'application/msword'
  });
  
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename.endsWith('.doc') ? filename : `${filename}.doc`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
};
